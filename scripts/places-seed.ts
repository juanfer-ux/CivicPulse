// One-off (owner, 2026-11-20): asks Overpass (OpenStreetMap) for the places around each seed recurrence and writes supabase/seed/recurrence_places.sql.
// Run: node scripts/places-seed.ts   (Node 23.6+ runs TypeScript as is; no keys, nothing is sent but coordinates.)
// Slow on purpose: the public servers are busy, so it waits between calls and retries on the other server.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { kindOf, labelOf } from '../src/lib/places.ts'

const FETCH_M = 130 // the SQL keeps what is within 100 m of the recurrence's own coordinates; the seed points can sit up to about 25 m away from them
const SERVERS = ['https://overpass-api.de/api/interpreter', 'https://overpass.kumi.systems/api/interpreter']
const seed = readFileSync(new URL('../supabase/seed/synthetic_problems.sql', import.meta.url), 'utf8')
const points = [...seed.matchAll(/\('((?:PK|DM)[A-Z]*\d+)', '\w+', \d+, ([\d.]+), (-[\d.]+),/g)].map((m) => ({ pk: m[1], lat: Number(m[2]), lng: Number(m[3]) }))
if (points.length !== 20) throw new Error(`expected 20 seed points, found ${points.length}`)

type El = { type: string; id: number; lat?: number; lon?: number; center?: { lat: number; lon: number }; tags?: Record<string, string> }
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms))
// One call per point (the public server answers even a tiny query in 30 s on a bad day, so seven calls per point would take hours); a cache in the temp folder, so a rerun only asks what is missing.
const CACHE = join(tmpdir(), 'places-seed-cache-v2.json')
const cache: Record<string, El[]> = existsSync(CACHE) ? JSON.parse(readFileSync(CACHE, 'utf8')) : {}
async function ask(lat: number, lng: number): Promise<El[]> {
  const key = `${lat},${lng},${FETCH_M}`
  if (cache[key]) return cache[key]
  const around = `(around:${FETCH_M},${lat},${lng})`
  const q = `[out:json][timeout:150];(nwr${around}[~"^(amenity|shop|office|tourism|leisure|healthcare)$"~"."];nwr${around}[highway=bus_stop];);out tags center;`
  for (let attempt = 0; attempt < 6; attempt++) {
    try {
      const r = await fetch(SERVERS[attempt % SERVERS.length], { method: 'POST', body: new URLSearchParams({ data: q }), headers: { 'User-Agent': 'places-seed-script', Accept: 'application/json' }, signal: AbortSignal.timeout(170000) })
      if (r.ok) {
        cache[key] = ((await r.json()) as { elements: El[] }).elements
        writeFileSync(CACHE, JSON.stringify(cache))
        return cache[key]
      }
    } catch { /* try the next server */ }
    await sleep(15000)
  }
  throw new Error(`no answer for ${key}`)
}

const places = new Map<string, string>() // source_ref -> SQL row, so a place near two seed points is stored once
for (const p of points) {
  const els = await ask(p.lat, p.lng)
  let kept = 0
  for (const e of els) {
    const tags = e.tags ?? {}
    const kind = kindOf(tags)
    const c = e.center ?? (e.lat != null && e.lon != null ? { lat: e.lat, lon: e.lon } : null)
    if (!kind || !c) continue
    const q = (s: string) => `'${s.replace(/'/g, "''")}'`
    places.set(`${e.type}${e.id}`, `(${q(`${e.type}${e.id}`)}, ${q(kind)}, ${q(tags.name ?? '')}, ${q(labelOf(tags))}, ${c.lat}, ${c.lon})`)
    kept++
  }
  console.log(p.pk, els.length, 'elements,', kept, 'kept')
  await sleep(4000)
}

const today = new Date().toISOString().slice(0, 10)
writeFileSync(new URL('../supabase/seed/recurrence_places.sql', import.meta.url), `-- Places around each recurrence, from OpenStreetMap (Overpass), snapshot ${today}. Generated by scripts/places-seed.ts: do not edit by hand.
-- Run in the Supabase SQL editor AFTER migration 20261120000000_recurrence_places.sql and after the problems exist. Re-runnable: it replaces the rows of source 'osm'.
-- Each place goes to every recurrence within 100 m of it (public.geo_m), with its distance. © OpenStreetMap contributors (ODbL).
begin;
delete from public.recurrence_places where source = 'osm';
insert into public.recurrence_places (problem_id, source, source_ref, kind, name, label, lat, lng, dist_m, snapshot_at)
select p.id, 'osm', v.ref, v.kind, v.name, v.label, v.lat, v.lng, round(public.geo_m(p.lat, p.lng, v.lat, v.lng))::int, date '${today}'
from public.problems p
cross join (values
${[...places.values()].join(',\n')}
) as v(ref, kind, name, label, lat, lng)
where public.geo_m(p.lat, p.lng, v.lat, v.lng) <= 100;
commit;
`)
console.log('wrote', places.size, 'places')
